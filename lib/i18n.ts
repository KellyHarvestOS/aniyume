export const translations: Record<Language, Dictionary> = { ru, kk, en };

/**
 * Возвращает перевод по ключу. Если для выбранного языка ключа нет — откатывается
 * на русский, затем на сам ключ. Поддерживает подстановку `{name}` через `vars`.
 */
export function translate(
  lang: Language,
  key: string,
  vars?: Record<string, string | number>,
): string {
  const template = translations[lang]?.[key] ?? translations[DEFAULT_LANGUAGE][key] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name) =>
    name in vars ? String(vars[name]) : match,
  );
}
